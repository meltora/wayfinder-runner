package main

import (
	"encoding/base64"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"time"

	"github.com/example/app-runner/internal/safeio"
	"github.com/example/app-runner/internal/updatecatalog"
	"github.com/example/app-runner/internal/updatepublish"
)

const maxInputBytes = 4 << 20

func main() {
	if err := run(os.Args[1:], os.Stdout); err != nil {
		_, _ = fmt.Fprintln(os.Stderr, "error:", err)
		os.Exit(1)
	}
}

func run(args []string, stdout io.Writer) error {
	if len(args) == 0 {
		return fmt.Errorf("usage: update-manifest generate|assemble|check-trust [flags]")
	}
	switch args[0] {
	case "generate":
		return runGenerate(args[1:], stdout)
	case "assemble":
		return runAssemble(args[1:], stdout)
	case "check-trust":
		return runCheckTrust(args[1:], stdout)
	default:
		return fmt.Errorf("unknown command %q", args[0])
	}
}

func runGenerate(args []string, stdout io.Writer) error {
	flags := flag.NewFlagSet("generate", flag.ContinueOnError)
	flags.SetOutput(io.Discard)
	artifactsPath := flags.String("artifacts", "", "GoReleaser artifacts.json")
	distRoot := flags.String("dist", "dist", "GoReleaser distribution directory")
	baseURL := flags.String("base-url", "", "immutable release asset base URL")
	channel := flags.String("channel", "", "release channel")
	sequenceText := flags.String("sequence", "", "monotonic release sequence")
	releaseID := flags.String("release-id", "", "immutable release identifier")
	version := flags.String("version", "", "semantic version without v prefix")
	issuedText := flags.String("issued-at", "", "RFC3339 issuance time")
	expiresText := flags.String("expires-at", "", "RFC3339 expiration time")
	minRunner := flags.String("min-runner", "", "minimum runner version")
	minUpdater := flags.String("min-updater", "", "minimum updater version")
	payloadPath := flags.String("payload-out", "", "canonical payload output")
	digestPath := flags.String("digest-out", "", "32-byte signing digest output")
	if err := flags.Parse(args); err != nil || flags.NArg() != 0 {
		return fmt.Errorf("invalid generate flags")
	}
	sequence, err := strconv.ParseUint(*sequenceText, 10, 64)
	if err != nil || sequence == 0 {
		return fmt.Errorf("sequence must be a positive integer")
	}
	issuedAt, err := parseWholeSecondTime("issued-at", *issuedText)
	if err != nil {
		return err
	}
	expiresAt, err := parseWholeSecondTime("expires-at", *expiresText)
	if err != nil {
		return err
	}
	if *artifactsPath == "" || *payloadPath == "" || *digestPath == "" {
		return fmt.Errorf("artifacts, payload-out, and digest-out are required")
	}
	raw, err := safeio.ReadRegularFile(*artifactsPath, maxInputBytes, 0o022)
	if err != nil {
		return fmt.Errorf("read artifacts: %w", err)
	}
	manifest, err := updatepublish.Generate(raw, updatepublish.Options{
		DistRoot: *distRoot, BaseURL: *baseURL, Channel: *channel, Sequence: sequence,
		ReleaseID: *releaseID, Version: *version, IssuedAt: issuedAt, ExpiresAt: expiresAt,
		MinRunner: *minRunner, MinUpdater: *minUpdater,
	})
	if err != nil {
		return err
	}
	payload, err := updatecatalog.CanonicalPayload(manifest)
	if err != nil {
		return err
	}
	digest, err := updatecatalog.SigningDigest(manifest)
	if err != nil {
		return err
	}
	if err := atomicOutput(*payloadPath, append(payload, '\n'), 0o644); err != nil {
		return err
	}
	if err := atomicOutput(*digestPath, digest[:], 0o600); err != nil {
		return err
	}
	_, _ = fmt.Fprintf(stdout, "generated sequence %d for %s with %d artifacts\n", sequence, *version, len(manifest.Artifacts))
	return nil
}

type signatureFlags []string

func (values *signatureFlags) String() string { return strings.Join(*values, ",") }
func (values *signatureFlags) Set(value string) error {
	*values = append(*values, value)
	return nil
}

func runAssemble(args []string, stdout io.Writer) error {
	flags := flag.NewFlagSet("assemble", flag.ContinueOnError)
	flags.SetOutput(io.Discard)
	payloadPath := flags.String("payload", "", "canonical payload generated by this tool")
	outputPath := flags.String("output", "", "signed envelope output")
	var signatureArgs signatureFlags
	flags.Var(&signatureArgs, "signature", "key-id=base64-signature-file (repeatable)")
	if err := flags.Parse(args); err != nil || flags.NArg() != 0 {
		return fmt.Errorf("invalid assemble flags")
	}
	if *payloadPath == "" || *outputPath == "" || len(signatureArgs) == 0 {
		return fmt.Errorf("payload, output, and at least one signature are required")
	}
	payload, err := safeio.ReadRegularFile(*payloadPath, maxInputBytes, 0o022)
	if err != nil {
		return fmt.Errorf("read payload: %w", err)
	}
	payload = []byte(strings.TrimSuffix(string(payload), "\n"))
	manifest, err := updatecatalog.ParsePayload(payload)
	if err != nil {
		return fmt.Errorf("parse canonical payload: %w", err)
	}
	signatures := make([]updatecatalog.DetachedSignature, 0, len(signatureArgs))
	for _, item := range signatureArgs {
		keyID, path, ok := strings.Cut(item, "=")
		if !ok || keyID == "" || path == "" {
			return fmt.Errorf("signature must use key-id=path form")
		}
		raw, err := safeio.ReadRegularFile(path, 16<<10, 0o022)
		if err != nil {
			return fmt.Errorf("read signature %s: %w", keyID, err)
		}
		encoded := strings.TrimSpace(string(raw))
		decoded, err := base64.StdEncoding.DecodeString(encoded)
		if err != nil || base64.StdEncoding.EncodeToString(decoded) != encoded {
			return fmt.Errorf("signature %s is not canonical base64", keyID)
		}
		signatures = append(signatures, updatecatalog.DetachedSignature{KeyID: keyID, Value: decoded})
	}
	envelope, err := updatecatalog.Assemble(manifest, signatures)
	if err != nil {
		return err
	}
	if err := atomicOutput(*outputPath, append(envelope, '\n'), 0o644); err != nil {
		return err
	}
	_, _ = fmt.Fprintf(stdout, "assembled %d detached signatures\n", len(signatures))
	return nil
}

func parseWholeSecondTime(name, value string) (time.Time, error) {
	parsed, err := time.Parse(time.RFC3339, value)
	if err != nil || parsed.Nanosecond() != 0 || parsed.Location() != time.UTC || parsed.Format(time.RFC3339) != value {
		return time.Time{}, fmt.Errorf("%s must use whole-second UTC RFC3339 form", name)
	}
	return parsed, nil
}

func atomicOutput(path string, data []byte, mode os.FileMode) error {
	if path == "" {
		return fmt.Errorf("output path is required")
	}
	abs, err := filepath.Abs(path)
	if err != nil {
		return err
	}
	dir := filepath.Dir(abs)
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return err
	}
	if err := safeio.AtomicWriteFile(dir, filepath.Base(abs), data, mode); err != nil {
		return fmt.Errorf("write %s: %w", path, err)
	}
	return nil
}
